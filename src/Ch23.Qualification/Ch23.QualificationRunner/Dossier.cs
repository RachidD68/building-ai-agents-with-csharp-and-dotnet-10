using System.Text;
using System.Text.Json;

namespace Ch23.QualificationRunner;

public sealed record JournalEntry(string Id, string Layer, string? Row, string Finding, string Disposition, string Reason);
public sealed record DecisionRecord(string Decision, string Acceptance, List<string> Conditions);
public sealed record FailureJournal(List<JournalEntry> Entries, DecisionRecord Decision);
public sealed record Capability(string Name, List<string> Routes, bool Enabled, string? Reason);
public sealed record CapabilityFile(string Profile, List<Capability> Capabilities);

/// <summary>
/// The release dossier, rendered from qualification-results.json, the failure journal
/// and the capability file. Every count in it is read from the results; the journal
/// names rows, and the dossier prints what the run observed for each.
/// </summary>
public static class Dossier
{
    public static readonly string[] Dispositions = ["fixed", "known-limitation", "capability-disabled", "deferred"];

    public static string Render(QualificationResults r, FailureJournal journal, CapabilityFile caps, IReadOnlyList<string> limits)
    {
        List<string> problems = [.. journal.Entries.Where(e => !Dispositions.Contains(e.Disposition)).Select(e => $"{e.Id}: unknown disposition '{e.Disposition}'")];
        problems.AddRange(journal.Entries.Where(e => e.Row is not null && r.Matrix.All(m => m.Id != e.Row)).Select(e => $"{e.Id}: row {e.Row} is not in the matrix"));
        problems.AddRange(caps.Capabilities.Where(c => !c.Enabled && string.IsNullOrWhiteSpace(c.Reason)).Select(c => $"capability {c.Name} is disabled without a reason"));
        problems.AddRange(r.Matrix.Where(m => m.Status is Matrix.Failed or Matrix.Refused or Matrix.NotRun && journal.Entries.All(e => e.Row != m.Id))
            .Select(m => $"row {m.Id} is {m.Status} and has no journal entry"));
        if (problems.Count > 0) throw new InvalidDataException("dossier refused:\n  " + string.Join("\n  ", problems));

        StringBuilder s = new();
        CandidateIdentity c = r.Candidate;
        s.AppendLine($"# Release dossier: {c.Candidate}\n");
        s.AppendLine("Generated by Ch23.QualificationRunner from `qualification-results.json`. Do not edit by hand; rerun `--dossier`.\n");
        s.AppendLine("## Candidate\n");
        s.AppendLine($"- identity sha256 `{r.CandidateSha256}` (unchanged after the run: {(r.IdentityUnchangedAfterRun ? "yes" : "NO")})");
        s.AppendLine($"- runs: {string.Join(", ", r.Modes)}; {r.StartedUtc} to {r.FinishedUtc} UTC; {r.Platform}; SDK used {r.SdkUsed} (global.json asks {c.GlobalJsonSdk})");
        s.AppendLine($"- {c.Packages.Count} direct packages, {c.LockFiles.Count} lock files; prerelease: {string.Join(", ", CandidateIdentity.PrereleaseIds(c).DefaultIfEmpty("none"))}");
        s.AppendLine($"- profile: {c.Profile.ConfigurationProfile}, provider {c.Profile.Provider}, chat model {c.Profile.ChatModel}{(c.Profile.EmbeddingModel is null ? "" : $", embeddings {c.Profile.EmbeddingModel}")}");
        if (r.Model is { } m) s.AppendLine($"- model as observed: {m.Name}, digest {m.Digest ?? "not read"}, response model id {m.ResponseModelId ?? "not read"}");
        s.AppendLine($"- prompts: {string.Join(", ", c.Prompts.Select(p => $"{p.Id} {p.Sha256[..Math.Min(12, p.Sha256.Length)]}"))}");
        s.AppendLine($"- skills: {string.Join(", ", c.Skills.Select(k => $"{k.Name} {k.Version} {k.Sha256[..12]} (lock {(k.Match ? "matches" : "DIFFERS")})"))}");
        s.AppendLine($"- data: {string.Join(", ", c.Data.Select(d => $"{d.Id} ({d.Files} files) {d.Sha256[..12]}"))}\n");

        s.AppendLine("## Layers\n");
        s.AppendLine("| Layer | Steps | Cases passed | Status | Proves | Does not prove |");
        s.AppendLine("|---|---|---|---|---|---|");
        foreach (LayerResult l in r.Layers)
            s.AppendLine($"| {l.Title} | {l.Steps.Count} | {l.Steps.Sum(x => x.Passed)}/{l.Steps.Sum(x => x.Total)} | {l.Status} | {l.Proves} | {l.DoesNotProve} |");
        s.AppendLine();
        List<StepResult> odd = [.. r.Layers.SelectMany(l => l.Steps).Where(x => x.Status is not (StepStatus.Passed or StepStatus.Completed))];
        foreach (StepResult x in odd) s.AppendLine($"- `{x.Id}`: {x.Status}, {x.Reason}");
        if (odd.Count > 0) s.AppendLine();

        s.AppendLine("## Acceptance matrix\n");
        s.AppendLine("| Row | Promise | Evidence | Test | Data | Expected | Status | Observed | Artifact |");
        s.AppendLine("|---|---|---|---|---|---|---|---|---|");
        foreach (RowResult row in r.Matrix)
            s.AppendLine($"| {row.Id} | {row.Promise} | {row.Evidence} | {Esc(row.Test)} | {row.Data} | {row.Expected} | {row.Status} | {Esc(row.Observed)} | {row.Artifact ?? "-"} |");
        s.AppendLine();

        s.AppendLine("## Failure journal\n");
        s.AppendLine("| Id | Layer | Row | Observed | Finding | Disposition | Reason |");
        s.AppendLine("|---|---|---|---|---|---|---|");
        foreach (JournalEntry e in journal.Entries)
        {
            RowResult? row = r.Matrix.FirstOrDefault(x => x.Id == e.Row);
            s.AppendLine($"| {e.Id} | {e.Layer} | {e.Row ?? "-"} | {(row is null ? "-" : $"{row.Status} {Esc(row.Observed)}")} | {e.Finding} | {e.Disposition} | {e.Reason} |");
        }
        s.AppendLine();

        s.AppendLine($"## Capabilities ({caps.Profile} profile)\n");
        foreach (Capability cap in caps.Capabilities)
            s.AppendLine($"- `{cap.Name}` ({string.Join(", ", cap.Routes)}): {(cap.Enabled ? "enabled" : "DISABLED, " + cap.Reason)}");
        s.AppendLine("\n## Known limitations\n");
        foreach (string l in limits) s.AppendLine($"- {l}");
        s.AppendLine("\n## Decision record\n");
        s.AppendLine($"- candidate: {c.Candidate}, identity `{r.CandidateSha256[..16]}`");
        s.AppendLine($"- evidence: qualification-results.json, {r.Totals.CasesPassed}/{r.Totals.Cases} cases passed over {r.Totals.Steps} steps; matrix {r.Totals.RowsPassed} passed, {r.Totals.RowsFailed} failed, {r.Totals.RowsNotRun} not run, {r.Totals.RowsRefused} refused, {r.Totals.RowsPendingHuman} pending human acceptance");
        s.AppendLine($"- decision: {journal.Decision.Decision}");
        s.AppendLine($"- human acceptance: {journal.Decision.Acceptance}");
        foreach (string cond in journal.Decision.Conditions) s.AppendLine($"- condition: {cond}");
        return s.ToString();
    }

    private static string Esc(string? text) => text is null ? "-" : text.Replace("|", "\\|", StringComparison.Ordinal);

    public static T Load<T>(string path) => JsonSerializer.Deserialize<T>(File.ReadAllText(path), CandidateManifest.Json)
        ?? throw new InvalidDataException($"empty {path}");
}
