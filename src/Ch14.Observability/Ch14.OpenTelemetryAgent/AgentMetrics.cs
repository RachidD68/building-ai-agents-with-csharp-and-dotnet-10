using System.Diagnostics;
using System.Diagnostics.Metrics;

namespace Ch14.OpenTelemetryAgent;

/// <summary>
/// Custom metrics for monitoring agent interactions.
/// Tracks token usage, response latency, and tool call counts
/// using the System.Diagnostics.Metrics API.
/// </summary>
public sealed class AgentMetrics : IDisposable
{
    /// <summary>
    /// The meter name used for agent telemetry.
    /// Use this when configuring OpenTelemetry meter providers.
    /// </summary>
    public const string MeterName = "AgenticAI.Agent";

    /// <summary>
    /// The activity source name used for distributed tracing.
    /// Use this when configuring OpenTelemetry tracer providers.
    /// </summary>
    public const string ActivitySourceName = "AgenticAI.Agent";

    private readonly Meter _meter;
    private readonly Counter<long> _inputTokens;
    private readonly Counter<long> _outputTokens;
    private readonly Counter<long> _requestCount;
    private readonly Histogram<double> _latency;
    private readonly Counter<long> _toolCallCount;
    private readonly Counter<long> _errorCount;
    private readonly Histogram<double> _costUsd;
    private readonly Histogram<double> _evalPassRate;

    // Pricing table (USD per 1,000,000 tokens). Read from configuration so the
    // rates never get baked into a binary — provider prices change often.
    private readonly double _inputRatePerMillion;
    private readonly double _outputRatePerMillion;

    /// <summary>
    /// Gets the activity source for creating distributed trace spans.
    /// </summary>
    public ActivitySource ActivitySource { get; }

    /// <summary>
    /// Initializes a new instance of <see cref="AgentMetrics"/>.
    /// </summary>
    /// <param name="inputRatePerMillion">
    /// Price in USD per 1,000,000 input tokens, from configuration
    /// (<c>Pricing:InputPerMillion</c>). Defaults to 0 when unset.
    /// </param>
    /// <param name="outputRatePerMillion">
    /// Price in USD per 1,000,000 output tokens, from configuration
    /// (<c>Pricing:OutputPerMillion</c>). Defaults to 0 when unset.
    /// </param>
    public AgentMetrics(double inputRatePerMillion = 0.0, double outputRatePerMillion = 0.0)
    {
        _inputRatePerMillion = inputRatePerMillion;
        _outputRatePerMillion = outputRatePerMillion;

        _meter = new Meter(MeterName, "1.0.0");
        ActivitySource = new ActivitySource(ActivitySourceName, "1.0.0");

        _inputTokens = _meter.CreateCounter<long>(
            "agent.tokens.input",
            unit: "tokens",
            description: "Total input tokens consumed by the agent");

        _outputTokens = _meter.CreateCounter<long>(
            "agent.tokens.output",
            unit: "tokens",
            description: "Total output tokens generated by the agent");

        _requestCount = _meter.CreateCounter<long>(
            "agent.requests.total",
            unit: "requests",
            description: "Total number of agent requests");

        _latency = _meter.CreateHistogram<double>(
            "agent.request.duration",
            unit: "ms",
            description: "Duration of agent requests in milliseconds");

        _toolCallCount = _meter.CreateCounter<long>(
            "agent.tools.invocations",
            unit: "calls",
            description: "Total number of tool invocations");

        _errorCount = _meter.CreateCounter<long>(
            "agent.errors.total",
            unit: "errors",
            description: "Total number of agent errors");

        _costUsd = _meter.CreateHistogram<double>(
            "agent.cost.usd",
            unit: "USD",
            description: "Estimated USD cost per agent request, from token usage × configured rates");

        _evalPassRate = _meter.CreateHistogram<double>(
            "agent.eval.pass_rate",
            unit: "ratio",
            description: "Fraction of evaluation checks that passed (0.0–1.0) — quality as a dashboard signal");
    }

    /// <summary>
    /// Records token usage from an agent response.
    /// </summary>
    /// <param name="inputTokens">Number of input tokens consumed.</param>
    /// <param name="outputTokens">Number of output tokens generated.</param>
    /// <param name="agentName">The name of the agent for tagging.</param>
    public void RecordTokenUsage(long inputTokens, long outputTokens, string agentName)
    {
        _inputTokens.Add(inputTokens, new KeyValuePair<string, object?>("agent.name", agentName));
        _outputTokens.Add(outputTokens, new KeyValuePair<string, object?>("agent.name", agentName));
    }

    /// <summary>
    /// Records a completed agent request with its duration.
    /// </summary>
    /// <param name="durationMs">The request duration in milliseconds.</param>
    /// <param name="agentName">The name of the agent for tagging.</param>
    public void RecordRequest(double durationMs, string agentName)
    {
        _requestCount.Add(1, new KeyValuePair<string, object?>("agent.name", agentName));
        _latency.Record(durationMs, new KeyValuePair<string, object?>("agent.name", agentName));
    }

    /// <summary>
    /// Records the estimated USD cost of a request, derived from token usage and
    /// the configured pricing table, and emits it on the <c>agent.cost.usd</c>
    /// histogram. Cost is a first-class signal: it rides the same export pipeline
    /// as latency and token counts, so a cost regression shows up on the same
    /// dashboards — before the monthly bill does.
    /// </summary>
    /// <param name="inputTokens">Input tokens consumed by the request.</param>
    /// <param name="outputTokens">Output tokens produced by the request.</param>
    /// <param name="agentName">The name of the agent for tagging.</param>
    /// <returns>The estimated cost in USD that was recorded.</returns>
    public double RecordCost(long inputTokens, long outputTokens, string agentName)
    {
        double cost = (inputTokens / 1_000_000.0 * _inputRatePerMillion)
                    + (outputTokens / 1_000_000.0 * _outputRatePerMillion);

        _costUsd.Record(cost, new KeyValuePair<string, object?>("agent.name", agentName));
        return cost;
    }

    /// <summary>
    /// Records an evaluation pass rate (0.0–1.0) on the <c>agent.eval.pass_rate</c>
    /// histogram. This is the "fourth signal": traces, metrics, and logs tell you
    /// the call ran; the pass rate tells you the answers were actually good — and it
    /// rides the same export pipeline as latency and cost, so quality lands on the
    /// same dashboards. The evaluation framework that produces the rate is Chapter
    /// 17's subject; here we only record the number.
    /// </summary>
    /// <param name="passRate">Fraction of evaluated items that passed, 0.0–1.0.</param>
    /// <param name="agentName">The name of the agent for tagging.</param>
    public void RecordEvalPassRate(double passRate, string agentName)
    {
        _evalPassRate.Record(passRate, new KeyValuePair<string, object?>("agent.name", agentName));
    }

    /// <summary>
    /// Records a tool invocation.
    /// </summary>
    /// <param name="toolName">The name of the tool that was invoked.</param>
    /// <param name="agentName">The name of the agent that invoked the tool.</param>
    public void RecordToolCall(string toolName, string agentName)
    {
        _toolCallCount.Add(1,
            new KeyValuePair<string, object?>("tool.name", toolName),
            new KeyValuePair<string, object?>("agent.name", agentName));
    }

    /// <summary>
    /// Records an agent error.
    /// </summary>
    /// <param name="errorType">The type of error that occurred.</param>
    /// <param name="agentName">The name of the agent for tagging.</param>
    public void RecordError(string errorType, string agentName)
    {
        _errorCount.Add(1,
            new KeyValuePair<string, object?>("error.type", errorType),
            new KeyValuePair<string, object?>("agent.name", agentName));
    }

    /// <inheritdoc/>
    public void Dispose()
    {
        _meter.Dispose();
        ActivitySource.Dispose();
    }
}
